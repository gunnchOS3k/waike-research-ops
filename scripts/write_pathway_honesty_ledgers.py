#!/usr/bin/env python3
"""Derive pathway honesty ledgers from COURSE_DIGITAL_RC.json and the on-disk tree.

Keys under COURSE_DIGITAL_RC.json are not the same as COURSE_DIGITAL_RC=true:
a keyed course that fails the writer gate is a named residual, never a pass.
"""
from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ART = ROOT / "artifacts"


def _load(name: str) -> dict:
    return json.loads((ART / name).read_text(encoding="utf-8"))


def _dump(name: str, payload: dict) -> None:
    (ART / name).write_text(json.dumps(payload, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def main() -> int:
    now = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    rc = _load("COURSE_DIGITAL_RC.json")
    catalog = json.loads((ROOT / "curriculum/taxonomy/eighteen_tracks.json").read_text(encoding="utf-8"))
    catalog_ids = sorted(t.get("track_id") or t.get("id") for t in catalog["tracks"])
    on_disk = sorted(p.name for p in (ROOT / "curriculum/digital_rc").iterdir() if p.is_dir())
    keys = sorted(rc["courses"])
    true_ids = sorted(k for k, row in rc["courses"].items() if row.get("COURSE_DIGITAL_RC") is True)
    keyed_failing = sorted(k for k in keys if k not in true_ids)
    dirs_not_keyed = sorted(set(on_disk) - set(keys))
    alias = _load("CATALOG_ALIAS_HONESTY.json")
    aliased = {row["catalog_track_id"] for row in alias["aliases"]}
    catalog_missing = sorted(c for c in catalog_ids if c not in on_disk and c not in aliased)
    not_true = sorted(set(keyed_failing) | set(dirs_not_keyed) | set(catalog_missing))
    full_18 = False
    own_true = sorted(c for c in catalog_ids if c in true_ids)
    alias_only = sorted(c for c in catalog_ids if c in aliased and c not in true_ids)
    full_18_missing = {
        "catalog_ids_with_own_true_package": len(own_true),
        "catalog_track_ids": len(catalog_ids),
        "alias_only_catalog_ids": alias_only,
        "writer_computes_full_18": False,
        "needed": [
            "write_course_digital_rc.py has no full_18 computation; the flag is fixed False.",
            "Alias-only catalog IDs need either their own distinct packages or an owner policy that accepts aliases.",
        ],
    }

    ledger = _load("PATHWAY_DISK_VS_CATALOG_LEDGER.json")
    ledger.update({
        "prepared_at": now,
        "full_18_course_digital_rc": full_18,
        "counts": {
            "catalog_track_ids": len(catalog_ids),
            "digital_rc_dirs_on_disk": len(on_disk),
            "course_digital_rc_keys": len(keys),
            "course_digital_rc_true": len(true_ids),
        },
        "digital_rc_dirs_on_disk": on_disk,
        "course_digital_rc_keys": keys,
        "dirs_present_not_in_course_digital_rc_keys": dirs_not_keyed,
        "keyed_courses_failing_digital_rc_gate": keyed_failing,
        "catalog_missing_digital_rc_dir": catalog_missing,
        "notes": [
            "Generated by scripts/write_pathway_honesty_ledgers.py from COURSE_DIGITAL_RC.json.",
            "A key under COURSE_DIGITAL_RC.json is evaluated, not passed; failing keyed courses are named residuals.",
            "Dir presence and RC pass are not instructional completeness or HUMAN curriculum acceptance.",
        ],
    })
    _dump("PATHWAY_DISK_VS_CATALOG_LEDGER.json", ledger)

    stamp = _load("DIGITAL_RC_HONESTY_STAMP.json")
    stamp.update({
        "prepared_at": now,
        "full_18_course_digital_rc": full_18,
        "course_digital_rc_true_count": len(true_ids),
        "course_digital_rc_true_ids": true_ids,
        "course_digital_rc_not_true_ids": not_true,
        "catalog_vs_true_gap_count": len(catalog_ids) - len(keys),
        "catalog_vs_true_gap_note": (
            f"{len(catalog_ids)} catalog track IDs vs {len(keys)} COURSE_DIGITAL_RC keys; "
            f"{len(true_ids)} keys pass the writer gate. Remaining catalog IDs are aliases "
            "and must not be invented as new digital-RC courses."
        ),
        "full_18_missing": full_18_missing,
    })
    _dump("DIGITAL_RC_HONESTY_STAMP.json", stamp)

    residual = _load("FULL_18_RESIDUAL_HONESTY.json")
    rows = []
    for cid in not_true:
        if cid in keyed_failing:
            reasons = rc["courses"][cid].get("rc_fail_reasons") or []
            rows.append({
                "id": cid,
                "kind": "keyed_course_fails_digital_rc_gate",
                "invent_course_digital_rc_true": False,
                "rc_fail_reasons": reasons,
                "note": "Evaluated by write_course_digital_rc.py and failed; fix content, never the flag.",
            })
        elif cid in dirs_not_keyed:
            rows.append({
                "id": cid,
                "kind": "dir_present_without_course_digital_rc_key",
                "invent_course_digital_rc_true": False,
                "note": "On-disk package not evaluated by the writer; do not invent a true flag.",
            })
        else:
            rows.append({
                "id": cid,
                "kind": "catalog_only_no_digital_rc_dir",
                "invent_course_digital_rc_true": False,
                "note": "Catalog track only - no digital_rc dir. Research overlay stays HUMAN_PENDING; do not invent a 19th course or flip full_18.",
            })
    residual.update({"prepared_at": now, "full_18_course_digital_rc": full_18, "residuals": rows, "full_18_missing": full_18_missing})
    residual.pop("course_digital_rc_not_true_ids", None)
    _dump("FULL_18_RESIDUAL_HONESTY.json", residual)

    alias.update({"prepared_at": now, "full_18_course_digital_rc": full_18, "residuals_not_aliased_to_true": not_true})
    _dump("CATALOG_ALIAS_HONESTY.json", alias)

    discovery = _load("PATHWAY_DISCOVERY_HONESTY.json")
    discovery["prepared_at"] = now
    discovery["full_18_course_digital_rc"] = full_18
    discovery["discovery"].update({
        "digital_rc_dirs_with_course_json": sum(1 for d in on_disk if (ROOT / "curriculum/digital_rc" / d / "course.json").exists()),
        "course_digital_rc_keys": len(keys),
        "course_digital_rc_true_count": len(true_ids),
        "residuals_must_stay_not_true": not_true,
    })
    _dump("PATHWAY_DISCOVERY_HONESTY.json", discovery)

    print(json.dumps({"true": len(true_ids), "keys": len(keys), "not_true": not_true, "full_18": full_18}, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
