def rebalance_mcq(items: list[dict[str, Any]], offset: int = 0) -> list[dict[str, Any]]:
    """Place the correct choice on a rotating A/B/C/D slot. Preserves choice text."""
    out: list[dict[str, Any]] = []
    for i, item in enumerate(items):
        choices = list(item["choices"])
        ans = int(item["answer_index"])
        correct = choices[ans]
        rest = [c for j, c in enumerate(choices) if j != ans]
        n = len(choices)
        pos = (i + offset) % n
        new_choices = rest[:]
        new_choices.insert(pos, correct)
        row = dict(item)
        row["choices"] = new_choices
        row["answer_index"] = pos
        out.append(row)
    return out


